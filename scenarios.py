def generate_scenario(player_count):
    """Генерирует сценарий, гарантируя, что мест в бункере ВСЕГДА меньше, чем игроков"""
    catastrophe = random.choice(CATASTROPHES)
    bunker_template = random.choice(BUNKERS)
    
    # Вместимость = игроки минус 1 (чтобы каждый раунд изгонять ровно 1 человека)
    # max(1, ...) гарантирует, что вместимость не будет 0 или отрицательной
    safe_capacity = max(1, player_count - 1)
    
    bunker = {
        "name": bunker_template["name"],
        "capacity": safe_capacity,
        "resources": bunker_template["resources"],
        "features": bunker_template["features"]
    }
    
    return {"catastrophe": catastrophe, "bunker": bunker}