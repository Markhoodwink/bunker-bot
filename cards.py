def generate_card():
    """Генерирует случайную карточку персонажа"""
    return {
        "profession": random.choice(PROFESSIONS),
        "health": random.choice(HEALTH),
        "skill": random.choice(SKILLS),
        "hobby": random.choice(HOBBIES),
        "inventory": random.choice(INVENTORY)
    }


def generate_cards_for_players(count):
    """Генерирует уникальные карточки для всех игроков"""
    cards = []
    for _ in range(count):
        cards.append(generate_card())
    return cards